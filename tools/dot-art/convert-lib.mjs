// Turns Dot's SVG artwork (docs/dot-art/) into data the app renders and the certificate canvas
// draws. It also checks each file against the art brief and throws a clear message otherwise.

export const POSES = ['happy', 'thinking', 'cheering', 'curious'];
export const PARTS = ['antenna', 'body', 'arms', 'freckles', 'eyes', 'mouth'];
const SHAPES = ['circle', 'ellipse', 'path'];
const NUMERIC = ['cx', 'cy', 'r', 'rx', 'ry'];

/** The brief's palette. Ink becomes "outline" or "face" depending on the part it is in. */
const COLORS = {
  '#ffc93c': 'accent',
  '#ffffff': 'white',
  '#1b1f4b': 'ink',
  '#2457e6': 'number',
  '#0b7a3b': 'string',
  '#6d3bd2': 'boolean',
  '#c25a00': 'object',
  '#e0a100': 'array',
  '#c2187a': 'function',
  '#0e8f94': 'variable',
  '#c62828': 'html',
};
/** Ink on these parts sits on the yellow body (eyes, mouth); elsewhere it is the outer outline. */
const FACE_PARTS = ['eyes', 'mouth'];

function attributes(source) {
  const attrs = {};
  for (const [, name, value] of source.matchAll(/([\w:-]+)="([^"]*)"/g)) attrs[name] = value;
  return attrs;
}

function role(color, part, where) {
  if (color === undefined || color === 'none') return undefined;
  const r = COLORS[color.toLowerCase()];
  if (!r) throw new Error(`${where}: color ${color} is not in the brief's palette.`);
  return r === 'ink' ? (FACE_PARTS.includes(part) ? 'face' : 'outline') : r;
}

/** Converts one pose's SVG text. `name` is used in error messages. */
export function convertPose(svg, name) {
  const at = (msg) => new Error(`${name}: ${msg}`);
  const tags = [...svg.matchAll(/<(\/?)([\w:-]+)([^>]*?)(\/?)>/g)];
  if (!tags.length || tags[0][2] !== 'svg') throw at('must start with an <svg> element.');
  const root = attributes(tags[0][3]);
  if (root.viewBox !== '0 0 120 130') throw at(`viewBox must be "0 0 120 130", got "${root.viewBox}".`);
  if (root.width || root.height) throw at('the <svg> must not set width or height.');

  const stack = []; // open <g> elements: { part?, transform? }
  const shapes = [];
  const parts = new Set();
  let transform;
  for (const [, closing, tag, rest, selfClosing] of tags.slice(1)) {
    if (tag === 'svg' && closing) break;
    if (tag === 'g') {
      if (closing) stack.pop();
      else {
        const a = attributes(rest);
        if (a.id && !PARTS.includes(a.id)) throw at(`unknown part id "${a.id}". Use: ${PARTS.join(', ')}.`);
        if (a.transform) {
          if (stack.length || transform) throw at('only one transform, on an outer group, is supported.');
          transform = a.transform;
        }
        if (a.id) parts.add(a.id);
        stack.push({ part: a.id });
      }
      continue;
    }
    if (closing) continue;
    if (!SHAPES.includes(tag)) throw at(`<${tag}> is not supported. Use ${SHAPES.join(', ')}.`);
    if (!selfClosing) throw at(`<${tag}> must be self-closing.`);
    const part = [...stack].reverse().find((g) => g.part)?.part;
    if (!part) throw at(`a <${tag}> is outside any part group.`);
    const a = attributes(rest);
    const where = `${name} ${part} <${tag}>`;
    const shape = { part, tag };
    for (const key of NUMERIC) if (a[key] !== undefined) shape[key] = Number(a[key]);
    if (a.d !== undefined) shape.d = a.d;
    const fill = role(a.fill, part, where);
    const stroke = role(a.stroke, part, where);
    if (fill) shape.fill = fill;
    if (stroke) {
      shape.stroke = stroke;
      shape.strokeWidth = Number(a['stroke-width'] ?? 1);
    }
    if (a.fill === undefined) throw at(`${where} needs a fill (use fill="none" for lines).`);
    shapes.push(shape);
  }
  for (const required of ['body', 'eyes', 'mouth']) {
    if (!parts.has(required)) throw at(`the "${required}" part is missing.`);
  }
  return transform ? { transform, shapes } : { shapes };
}

/** The generated TypeScript module (libs/visuals/src/lib/dot/dot-art.ts). */
export function toModule(art) {
  return `// GENERATED by tools/dot-art/convert.mjs from docs/dot-art/*.svg. Do not edit by hand:
// change the SVGs and run \`node tools/dot-art/convert.mjs\`. Artwork: CC BY-NC 4.0 (ADR 0006).
import type { Concept } from '@jic/shared';

export type DotPose = ${POSES.map((p) => `'${p}'`).join(' | ')};
export type DotPart = ${PARTS.map((p) => `'${p}'`).join(' | ')};
/** accent = body, outline = outer line (themed), face = eyes and mouth (always ink), white = eye whites. */
export type DotRole = 'accent' | 'outline' | 'face' | 'white' | Concept;

export interface DotShape {
  readonly part: DotPart;
  readonly tag: 'circle' | 'ellipse' | 'path';
  readonly cx?: number;
  readonly cy?: number;
  readonly r?: number;
  readonly rx?: number;
  readonly ry?: number;
  readonly d?: string;
  readonly fill?: DotRole;
  readonly stroke?: DotRole;
  readonly strokeWidth?: number;
}

export interface DotPoseArt {
  /** An SVG transform for the whole figure (curious tilts its head). */
  readonly transform?: string;
  readonly shapes: readonly DotShape[];
}

export const DOT_POSES: readonly DotPose[] = ${JSON.stringify(POSES)};

export const DOT_ART: Readonly<Record<DotPose, DotPoseArt>> = ${JSON.stringify(art, null, 2)};
`;
}
