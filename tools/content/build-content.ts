/**
 * Content build: validates content/course.yaml and content/lessons/*.yaml, then writes typed
 * TypeScript modules to libs/data-access/src/generated/ (gitignored).
 *
 *   npx nx run content:build       # validate + write libs/data-access/src/generated
 *   npx nx run content:validate    # validate only (no files written)
 *
 * Errors print as `file:line:col  path: message` and exit with code 1. Warnings never fail the build.
 * Nx runs it with plain Node (type stripping) plus tools/content/ts-resolve.mjs; see content/project.json.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';
import { isMap, LineCounter, parseDocument, type Document, type Node } from 'yaml';
import type { Course, Lesson } from '../../libs/shared/src/lib/lesson.ts';
import {
  checkCourseAgainstLessons,
  formatPath,
  type Issue,
  type IssuePath,
  validateCourse,
  validateLesson,
} from '../../libs/shared/src/lib/validate-lesson.ts';

const ROOT = process.cwd();
const CONTENT = join(ROOT, 'content');
const OUT = join(ROOT, 'libs/data-access/src/generated');
const checkOnly = process.argv.includes('--check');

interface Parsed {
  file: string;
  doc: Document;
  lines: LineCounter;
  data: unknown;
}

let errorCount = 0;
let warningCount = 0;

function parse(file: string): Parsed | undefined {
  const lines = new LineCounter();
  const doc = parseDocument(readFileSync(file, 'utf8'), { lineCounter: lines, prettyErrors: true });
  for (const err of doc.errors) {
    const pos = err.linePos?.[0];
    report(
      file,
      pos ? `${pos.line}:${pos.col}` : '1:1',
      'error',
      `YAML syntax: ${err.message.split('\n')[0]}`,
    );
  }
  if (doc.errors.length) return undefined;
  return { file, doc, lines, data: doc.toJS() };
}

/** Finds the line:col of the deepest existing node on the path (a missing key points at its parent). */
function locate({ doc, lines }: Parsed, path: IssuePath): string {
  for (let depth = path.length; depth >= 0; depth--) {
    const sub = path.slice(0, depth);
    const node = (sub.length ? doc.getIn(sub, true) : doc.contents) as Node | undefined;
    // Point at the key for a mapping entry, so "concept: strng" points at "concept".
    const parent = depth > 0 ? (doc.getIn(path.slice(0, depth - 1), true) as Node | undefined) : undefined;
    const keyNode = isMap(parent)
      ? parent.items.find((p) => (p.key as { value?: unknown } | null)?.value === path[depth - 1])?.key
      : undefined;
    const target = (keyNode as Node | undefined) ?? node;
    const offset = target?.range?.[0];
    if (offset !== undefined) {
      const { line, col } = lines.linePos(offset);
      return `${line}:${col}`;
    }
  }
  return '1:1';
}

function report(file: string, where: string, level: Issue['level'], message: string): void {
  const tag = level === 'error' ? 'error  ' : 'warning';
  console.log(`${relative(ROOT, file).replaceAll('\\', '/')}:${where}  ${tag}  ${message}`);
  if (level === 'error') errorCount++;
  else warningCount++;
}

function reportIssues(parsed: Parsed, issues: readonly Issue[]): void {
  for (const issue of issues) {
    report(
      parsed.file,
      locate(parsed, issue.path),
      issue.level,
      `${formatPath(issue.path)}: ${issue.message}`,
    );
  }
}

// --- read and validate -------------------------------------------------------

const coursePath = join(CONTENT, 'course.yaml');
const courseParsed = parse(coursePath);
let course: Course | undefined;
if (courseParsed) {
  const r = validateCourse(courseParsed.data);
  reportIssues(courseParsed, r.issues);
  course = r.value;
}

const lessonsDir = join(CONTENT, 'lessons');
const lessonFiles = readdirSync(lessonsDir)
  .filter((f) => f.endsWith('.yaml'))
  .sort();
const lessons: Lesson[] = [];
for (const name of lessonFiles) {
  const parsed = parse(join(lessonsDir, name));
  if (!parsed) continue;
  const r = validateLesson(parsed.data, { expectedId: basename(name, '.yaml') });
  reportIssues(parsed, r.issues);
  if (r.value) lessons.push(r.value);
}

if (course && courseParsed && lessons.length === lessonFiles.length) {
  reportIssues(courseParsed, checkCourseAgainstLessons(course, lessons));
}

const summary = `${lessonFiles.length} lesson file(s), ${errorCount} error(s), ${warningCount} warning(s)`;
if (errorCount > 0 || !course) {
  console.log(`\nContent check failed: ${summary}.`);
  process.exit(1);
}

// --- write typed modules -----------------------------------------------------

if (!checkOnly) {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(join(OUT, 'lessons'), { recursive: true });
  const header = '// GENERATED by tools/content/build-content.ts from content/. Do not edit.\n';
  const json = (v: unknown) => JSON.stringify(v, null, 2);

  writeFileSync(
    join(OUT, 'course.ts'),
    `${header}import type { Course } from '@jic/shared';\n\nexport const COURSE: Course = ${json(course)};\n`,
  );
  for (const lesson of lessons) {
    writeFileSync(
      join(OUT, 'lessons', `${lesson.id}.ts`),
      `${header}import type { Lesson } from '@jic/shared';\n\nconst lesson: Lesson = ${json(lesson)};\n\nexport default lesson;\n`,
    );
  }
  const loaders = lessons
    .map((l) => `  ${json(l.id)}: () => import('./lessons/${l.id}').then((m) => m.default),`)
    .join('\n');
  writeFileSync(
    join(OUT, 'index.ts'),
    `${header}import type { Lesson } from '@jic/shared';\n\nexport { COURSE } from './course';\n\n` +
      `/** One lazy chunk per lesson. */\nexport const LESSON_LOADERS: Readonly<Record<string, () => Promise<Lesson>>> = {\n${loaders}\n};\n`,
  );
}

console.log(`Content ${checkOnly ? 'is valid' : 'built'}: ${summary}.`);
